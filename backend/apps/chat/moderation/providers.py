"""
Moderation AI provider interfaces and implementations.

Providers:
  NullProvider            — allows all content, no external calls (default/dev mode).
  MockProvider            — configurable simulated latency + ground-truth rules for tests.
  HuggingFaceProvider     — async HTTP to HuggingFace Inference API (paid, requires credits).
  LocalTransformerProvider— on-device text classification using transformers + torch (free, offline).
  GeminiProvider          — Google Gemini API (free tier: 1,500 req/day via AI Studio).

Layer 3 contextual analysis produces a ContextualResult that the pipeline's
policy engine converts to a final ModerationResult verdict.
"""

import asyncio
import json
import logging
import time
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import List, Optional, Set

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Core result types
# ---------------------------------------------------------------------------

@dataclass
class ProviderResult:
    verdict: str  # "allowed", "blocked", "flagged"
    latency_ms: float = 0.0
    flagged: bool = False
    reason: str = ""
    raw_response: dict = field(default_factory=dict)

    @property
    def is_allowed(self) -> bool:
        return self.verdict == "allowed"

    @property
    def is_blocked(self) -> bool:
        return self.verdict == "blocked"

    @property
    def is_flagged(self) -> bool:
        return self.verdict == "flagged"


# Allowed literal values for intent_label and target_type.
_ALLOWED_INTENT_LABELS = frozenset({
    "unknown", "attack", "harassment", "threat", "insult",
    "mockery", "banter", "criticism", "quotation", "disagreement",
    "neutral", "insufficient_context",
})

_ALLOWED_TARGET_TYPES = frozenset({
    "unknown", "person", "group", "idea", "action",
    "self", "none", "insufficient_context",
})

_ALLOWED_ACTIONS = frozenset({"allow", "review", "block"})


@dataclass
class ContextualResult:
    """
    Structured output from the contextual analysis step.

    This is an internal contract — not all fields need to be surfaced
    through the public API.  Fields that the provider cannot supply are
    set to sentinel values (NaN / "unknown" / empty list) so callers
    can distinguish absence from zero.

    The policy engine treats this as *evidence*, not as an authoritative
    instruction.  Model-generated free-text (context_summary) is never
    executed or forwarded to the client.
    """

    # Per-attribute scores clamped to [0.0, 1.0].  NaN means unavailable.
    toxicity_score: float = float("nan")
    harassment_score: float = float("nan")
    threat_score: float = float("nan")
    insult_score: float = float("nan")

    sarcasm_detected: bool = False
    sarcasm_confidence: float = 0.0

    # Controlled-vocabulary fields — validated on construction.
    intent_label: str = "unknown"
    target_type: str = "unknown"

    # Short internal summary generated by the provider — never shown to
    # end-users or forwarded to the client.
    context_summary: str = ""

    # Overall confidence that the classification is reliable.
    confidence: float = 0.0

    # "allow" | "review" | "block"
    recommended_action: str = "allow"

    # Machine-readable codes explaining the recommendation.
    reason_codes: List[str] = field(default_factory=list)

    # Whether contextual analysis was actually performed.
    contextual_analysis_performed: bool = False

    # Whether the provider reported a transient failure.
    provider_failed: bool = False

    def __post_init__(self):
        # Clamp finite scores to [0.0, 1.0].
        import math
        for attr in ("toxicity_score", "harassment_score", "threat_score",
                     "insult_score", "sarcasm_confidence", "confidence"):
            v = getattr(self, attr)
            if not math.isnan(v):
                setattr(self, attr, max(0.0, min(1.0, float(v))))

        # Validate controlled-vocabulary fields.
        if self.intent_label not in _ALLOWED_INTENT_LABELS:
            logger.warning(
                "ContextualResult: invalid intent_label %r, resetting to 'unknown'",
                self.intent_label,
            )
            self.intent_label = "unknown"

        if self.target_type not in _ALLOWED_TARGET_TYPES:
            logger.warning(
                "ContextualResult: invalid target_type %r, resetting to 'unknown'",
                self.target_type,
            )
            self.target_type = "unknown"

        if self.recommended_action not in _ALLOWED_ACTIONS:
            logger.warning(
                "ContextualResult: invalid recommended_action %r, defaulting to 'allow'",
                self.recommended_action,
            )
            self.recommended_action = "allow"

        # Safety: truncate context_summary to prevent storing large payloads.
        if len(self.context_summary) > 500:
            self.context_summary = self.context_summary[:500]


def _safe_contextual_result(**kwargs) -> ContextualResult:
    """
    Build a ContextualResult from kwargs, catching any validation errors.
    Returns a provider_failed result on any exception.
    """
    try:
        return ContextualResult(**kwargs)
    except Exception as exc:
        logger.warning("Failed to build ContextualResult: %s", exc)
        return ContextualResult(
            provider_failed=True,
            reason_codes=["result_construction_error"],
        )


# ---------------------------------------------------------------------------
# Abstract base
# ---------------------------------------------------------------------------

class BaseModerationProvider(ABC):
    """
    Abstract interface for Layer 3 AI moderation providers.

    evaluate() returns a ProviderResult so that the existing pipeline
    contract is preserved.  Providers that also support contextual
    analysis should additionally implement evaluate_contextual().
    """

    def __init__(self):
        self.call_count: int = 0

    @abstractmethod
    async def evaluate(self, user, text: str) -> ProviderResult:
        """Evaluate text for moderation violations asynchronously."""
        pass

    async def evaluate_contextual(
        self,
        user,
        text: str,
        context: Optional[List[str]] = None,
    ) -> ContextualResult:
        """
        Optional contextual analysis extension.  Default implementation
        delegates to evaluate() and wraps the result as a ContextualResult.
        Providers that support richer analysis override this method.
        """
        result = await self.evaluate(user, text)
        action = "allow" if result.is_allowed else "block"
        return ContextualResult(
            toxicity_score=1.0 if result.is_blocked else 0.0,
            recommended_action=action,
            reason_codes=[result.reason] if result.reason else [],
            contextual_analysis_performed=False,
        )

    def reset_stats(self):
        self.call_count = 0


# ---------------------------------------------------------------------------
# Null provider — default, no external calls
# ---------------------------------------------------------------------------

class NullProvider(BaseModerationProvider):
    """
    Default null provider that allows all content without delay.
    Matches current behavior prior to external AI integration.
    """

    async def evaluate(self, user, text: str) -> ProviderResult:
        self.call_count += 1
        return ProviderResult(
            verdict="allowed",
            latency_ms=0.0,
            flagged=False,
            reason="null_provider_pass",
        )


# ---------------------------------------------------------------------------
# Mock provider — configurable rules for benchmarks and tests
# ---------------------------------------------------------------------------

class MockProvider(BaseModerationProvider):
    """
    Mock provider with configurable simulated latency and ground truth rules.
    Used for benchmarks and tests without hitting paid external APIs.
    """

    def __init__(
        self,
        latency_ms: float = 0.0,
        default_verdict: str = "allowed",
        toxic_words: Optional[Set[str]] = None,
    ):
        super().__init__()
        self.latency_ms = latency_ms
        self.default_verdict = default_verdict
        self.toxic_words = set(w.lower() for w in (toxic_words or []))

    async def evaluate(self, user, text: str) -> ProviderResult:
        self.call_count += 1
        if self.latency_ms > 0:
            await asyncio.sleep(self.latency_ms / 1000.0)

        verdict = self.default_verdict
        reason = "mock_provider_default"

        if self.toxic_words:
            lower = text.lower()
            for w in self.toxic_words:
                if w in lower:
                    verdict = "blocked"
                    reason = f"matched_ground_truth_toxic_word: {w}"
                    break

        return ProviderResult(
            verdict=verdict,
            latency_ms=self.latency_ms,
            flagged=(verdict == "flagged"),
            reason=reason,
        )

    async def evaluate_contextual(
        self,
        user,
        text: str,
        context: Optional[List[str]] = None,
    ) -> ContextualResult:
        """
        Mock contextual result: toxic words trigger a block, otherwise allow.
        Returns a deterministic ContextualResult for tests.
        """
        result = await self.evaluate(user, text)
        if result.is_blocked:
            return _safe_contextual_result(
                toxicity_score=1.0,
                harassment_score=0.5,
                threat_score=0.0,
                insult_score=0.5,
                confidence=0.95,
                recommended_action="block",
                intent_label="attack",
                target_type="person",
                reason_codes=["mock_toxic_word_match"],
                contextual_analysis_performed=True,
            )
        return _safe_contextual_result(
            toxicity_score=0.0,
            harassment_score=0.0,
            threat_score=0.0,
            insult_score=0.0,
            confidence=0.95,
            recommended_action="allow",
            intent_label="neutral",
            target_type="none",
            reason_codes=["mock_clean"],
            contextual_analysis_performed=True,
        )


# ---------------------------------------------------------------------------
# HuggingFace Inference API provider
# ---------------------------------------------------------------------------

class HuggingFaceProvider(BaseModerationProvider):
    """
    Contextual text-classification provider using the HuggingFace Inference API.

    Default model: unitary/toxic-bert
    - Returns per-label classification scores:
        toxic, severe_toxic, obscene, threat, insult, identity_hate
    - Endpoint: POST https://api-inference.huggingface.co/models/<model_id>
    - Input:  {"inputs": "<text>"}
    - Output: [[{"label": "toxic", "score": 0.95}, ...]]

    Configuration (via Django settings or constructor kwargs):
      HF_API_TOKEN       — HuggingFace read token (required for rate limits).
      HF_MODEL_ID        — Model identifier on HuggingFace Hub.
      HF_API_TIMEOUT     — Per-request timeout in seconds (default 5).
      HF_MAX_INPUT_LENGTH — Max characters sent to provider (default 512).

    Security:
      - Token read exclusively from settings; never logged or exposed.
      - Input text is passed as untrusted user content.
      - Model output is validated before use; free-text is never executed.
      - On any failure, returns controlled provider_failed=True result.

    Limitations:
      - Free-tier inference can have cold-start latency (1–5 s).
      - Rate limits apply; excess calls fall back to allow.
      - unitary/toxic-bert does not produce sarcasm scores natively;
        sarcasm heuristics are applied locally.
    """

    BASE_URL = "https://api-inference.huggingface.co/models"

    def __init__(
        self,
        api_token: Optional[str] = None,
        model_id: Optional[str] = None,
        timeout: Optional[float] = None,
        max_input_length: Optional[int] = None,
    ):
        super().__init__()
        from django.conf import settings

        raw_token = (
            api_token
            or getattr(settings, "HF_API_TOKEN", "")
            or ""
        )
        # Store token privately; do NOT log it.
        self._api_token = raw_token.strip()

        self.model_id = (
            model_id
            or getattr(settings, "HF_MODEL_ID", "unitary/toxic-bert")
        ).strip()

        self.timeout = (
            timeout
            if timeout is not None
            else float(getattr(settings, "GEMINI_API_TIMEOUT", 15))
        )

        self.max_input_length = (
            max_input_length
            if max_input_length is not None
            else int(getattr(settings, "HF_MAX_INPUT_LENGTH", 512))
        )

        self._endpoint = f"{self.BASE_URL}/{self.model_id}"
        self._client = None  # lazily created httpx.AsyncClient

    def _get_headers(self) -> dict:
        headers = {"Content-Type": "application/json"}
        if self._api_token:
            headers["Authorization"] = f"Bearer {self._api_token}"
        return headers

    def _truncate_input(self, text: str) -> str:
        """Truncate text to max_input_length to bound output size."""
        if len(text) > self.max_input_length:
            return text[: self.max_input_length]
        return text

    def _build_context_prefix(self, context: Optional[List[str]]) -> str:
        """
        Build a short context prefix from recent messages.
        Context is treated as untrusted user content — it is prepended as
        plain text and NOT interpreted as instructions.
        """
        if not context:
            return ""
        # Limit each context message and the total.
        truncated = []
        for msg in context[-5:]:  # at most 5 context messages
            msg = str(msg)[:200]  # cap each to 200 chars
            truncated.append(msg)
        return " [CONTEXT]: " + " | ".join(truncated) + " [MESSAGE]: "

    @staticmethod
    def _detect_sarcasm_heuristics(text: str) -> tuple:
        """
        Simple rule-based sarcasm heuristics.  Returns (detected, confidence).
        These are signals, not definitive classifications.

        Heuristics:
        - Multiple exclamation/question marks with positive words
        - "Oh great", "wow thanks", "sure" patterns
        - All-caps mixed with polite phrases
        - NOTE: sarcasm alone never triggers a block (policy engine enforces this).
        """
        lower = text.lower()
        markers = [
            "oh great", "oh wow", "wow thanks", "sure thing", "totally",
            "obviously", "yeah right", "oh really", "big surprise",
            "oh sure", "how wonderful", "love that for",
        ]
        has_marker = any(m in lower for m in markers)
        has_punct = text.count("!") >= 2 or text.count("?") >= 2
        has_caps_contrast = (
            text != text.lower()
            and text != text.upper()
            and sum(1 for c in text if c.isupper()) / max(len(text), 1) > 0.3
        )

        score = 0.0
        if has_marker:
            score += 0.4
        if has_punct:
            score += 0.2
        if has_caps_contrast:
            score += 0.15

        detected = score >= 0.4
        return detected, min(score, 1.0)

    def _parse_response(self, raw: object, text: str) -> ContextualResult:
        """
        Parse and validate the HuggingFace classification response.

        Expected shape: [[{"label": str, "score": float}, ...]]

        Invalid shapes, missing fields, out-of-range scores, and
        malformed JSON are all rejected — we never trust model output
        to execute any action directly.
        """
        import math

        # Validate top-level shape.
        if not isinstance(raw, list) or not raw:
            logger.warning(
                "HuggingFaceProvider: unexpected response shape: %r", type(raw)
            )
            return _safe_contextual_result(
                provider_failed=True,
                reason_codes=["invalid_response_shape"],
            )

        items = raw[0] if isinstance(raw[0], list) else raw
        if not isinstance(items, list):
            logger.warning(
                "HuggingFaceProvider: items is not a list: %r", type(items)
            )
            return _safe_contextual_result(
                provider_failed=True,
                reason_codes=["invalid_response_items"],
            )

        # Build score map, validating each entry.
        scores: dict = {}
        for entry in items:
            if not isinstance(entry, dict):
                continue
            label = entry.get("label", "")
            score = entry.get("score", None)
            if not isinstance(label, str) or not label:
                continue
            if score is None or not isinstance(score, (int, float)):
                continue
            score = float(score)
            if math.isnan(score) or math.isinf(score):
                continue
            scores[label.lower()] = max(0.0, min(1.0, score))

        if not scores:
            logger.warning(
                "HuggingFaceProvider: no valid scores parsed from response"
            )
            return _safe_contextual_result(
                provider_failed=True,
                reason_codes=["no_valid_scores"],
            )

        # Extract known labels (unitary/toxic-bert label set).
        toxicity = scores.get("toxic", float("nan"))
        harassment = scores.get("identity_hate", float("nan"))  # closest proxy
        threat = scores.get("threat", float("nan"))
        insult = scores.get("insult", float("nan"))
        obscene = scores.get("obscene", float("nan"))
        severe_toxic = scores.get("severe_toxic", float("nan"))

        # If "toxic" is available, use it as primary toxicity.
        # If severe_toxic is available and higher, prefer it.
        import math as _math
        if not _math.isnan(severe_toxic) and not _math.isnan(toxicity):
            toxicity = max(toxicity, severe_toxic)

        # Sarcasm heuristics (local, no extra API call).
        sarcasm_detected, sarcasm_confidence = self._detect_sarcasm_heuristics(text)

        # Determine overall confidence: if all primary scores are present,
        # confidence is high; if some are missing, lower it.
        available = sum(
            1 for s in (toxicity, harassment, threat, insult)
            if not _math.isnan(s)
        )
        confidence = 0.6 + 0.1 * available  # 0.6 to 1.0

        # Determine intent_label heuristically from score pattern.
        intent_label = "unknown"
        target_type = "unknown"
        reason_codes = []

        def _finite(s):
            return not _math.isnan(s)

        candidates = []
        if _finite(threat) and threat >= 0.5:
            candidates.append((threat, "threat", "person", "threat_score_elevated"))
        if _finite(harassment) and harassment >= 0.5:
            candidates.append((harassment, "harassment", "group", "harassment_score_elevated"))
        if _finite(toxicity) and toxicity >= 0.5:
            candidates.append((toxicity, "attack", "person", "toxicity_score_elevated"))
        if _finite(insult) and insult >= 0.5:
            candidates.append((insult, "insult", "person", "insult_score_elevated"))

        if candidates:
            candidates.sort(key=lambda c: c[0], reverse=True)
            _, intent_label, target_type, code = candidates[0]
            reason_codes.append(code)
        else:
            # All scores below 0.5 — likely benign.
            intent_label = "neutral"
            target_type = "none"

        # Sarcasm does not change the recommended action on its own.
        if sarcasm_detected:
            reason_codes.append("sarcasm_detected_heuristic")

        # Recommended action: leave the final decision to the policy engine.
        # Here we encode a preliminary recommendation without enforcing thresholds.
        max_score = max(
            (s for s in (toxicity, harassment, threat, insult, obscene or 0.0)
             if not _math.isnan(s)),
            default=0.0,
        )
        if max_score >= 0.85:
            recommended_action = "block"
        elif max_score >= 0.60:
            recommended_action = "review"
        else:
            recommended_action = "allow"

        return _safe_contextual_result(
            toxicity_score=toxicity,
            harassment_score=harassment,
            threat_score=threat,
            insult_score=insult,
            sarcasm_detected=sarcasm_detected,
            sarcasm_confidence=sarcasm_confidence,
            intent_label=intent_label,
            target_type=target_type,
            confidence=confidence,
            recommended_action=recommended_action,
            reason_codes=reason_codes,
            contextual_analysis_performed=True,
        )

    async def _call_api(self, payload: dict) -> object:
        """
        Perform a single HTTP POST to the HuggingFace Inference API.
        Returns parsed JSON or raises on error.
        """
        try:
            import httpx
        except ImportError:
            raise RuntimeError(
                "httpx is required for HuggingFaceProvider. "
                "Add httpx>=0.27 to requirements.txt."
            )

        headers = self._get_headers()
        body = json.dumps(payload).encode("utf-8")

        async with httpx.AsyncClient(timeout=self.timeout) as client:
            response = await client.post(
                self._endpoint,
                content=body,
                headers=headers,
            )

        if response.status_code == 401:
            raise PermissionError(
                f"HuggingFace API authentication failed (401). "
                f"Check HF_API_TOKEN."
            )
        if response.status_code == 402:
            raise RuntimeError(
                "HuggingFace API credits exhausted (402). "
                "HuggingFace serverless inference now requires paid credits. "
                "Switch to free MODERATION_PROVIDER=local or MODERATION_PROVIDER=gemini."
            )
        if response.status_code == 429:
            raise RuntimeError(
                "HuggingFace API rate limit exceeded (429)."
            )
        if response.status_code == 503:
            raise RuntimeError(
                f"HuggingFace model {self.model_id} is loading (503). "
                "Retry later or increase HF_API_TIMEOUT."
            )
        if response.status_code != 200:
            raise RuntimeError(
                f"HuggingFace API returned {response.status_code}: "
                f"{response.text[:200]}"
            )

        try:
            return response.json()
        except Exception as exc:
            raise ValueError(
                f"HuggingFace API returned non-JSON response: {exc}"
            ) from exc

    async def evaluate(self, user, text: str) -> ProviderResult:
        """
        Implements the BaseModerationProvider interface.
        Delegates to evaluate_contextual and converts the result.
        """
        self.call_count += 1
        ctx_result = await self.evaluate_contextual(user, text)

        if ctx_result.provider_failed:
            # Fail-safe: treat provider failure as allowed (do not block on uncertainty).
            return ProviderResult(
                verdict="allowed",
                latency_ms=0.0,
                flagged=False,
                reason="huggingface_provider_failure",
                raw_response={"provider_failed": True, "reason_codes": ctx_result.reason_codes},
            )

        verdict_map = {"allow": "allowed", "review": "flagged", "block": "blocked"}
        verdict = verdict_map.get(ctx_result.recommended_action, "allowed")
        reason = ",".join(ctx_result.reason_codes) if ctx_result.reason_codes else "hf_contextual"

        return ProviderResult(
            verdict=verdict,
            latency_ms=0.0,
            flagged=(verdict == "flagged"),
            reason=reason,
            raw_response={
                "toxicity_score": ctx_result.toxicity_score,
                "threat_score": ctx_result.threat_score,
                "insult_score": ctx_result.insult_score,
                "harassment_score": ctx_result.harassment_score,
                "sarcasm_detected": ctx_result.sarcasm_detected,
                "confidence": ctx_result.confidence,
                "intent_label": ctx_result.intent_label,
            },
        )

    async def evaluate_contextual(
        self,
        user,
        text: str,
        context: Optional[List[str]] = None,
    ) -> ContextualResult:
        """
        Run contextual analysis using the HuggingFace Inference API.

        Context is prepended as a short prefix; the model sees it as plain
        text.  We rely on the model's classification head, not on free-form
        instruction following, so prompt injection is not a concern for
        the classification labels.

        On any error (timeout, auth failure, malformed JSON, rate limit),
        returns a provider_failed=True result so the pipeline can apply its
        fail-safe policy.
        """
        start = time.perf_counter()

        # Truncate and optionally prepend context.
        context_prefix = self._build_context_prefix(context)
        input_text = self._truncate_input(context_prefix + text)

        payload = {"inputs": input_text}

        try:
            raw = await asyncio.wait_for(
                self._call_api(payload),
                timeout=self.timeout + 1.0,  # outer guard > inner httpx timeout
            )
        except asyncio.TimeoutError:
            logger.warning(
                "HuggingFaceProvider: request timed out after %.1fs for model %s",
                self.timeout,
                self.model_id,
            )
            return _safe_contextual_result(
                provider_failed=True,
                reason_codes=["provider_timeout"],
            )
        except PermissionError as exc:
            logger.error("HuggingFaceProvider: auth failure: %s", exc)
            return _safe_contextual_result(
                provider_failed=True,
                reason_codes=["provider_auth_failure"],
            )
        except RuntimeError as exc:
            msg = str(exc)
            if "402" in msg or "credits" in msg.lower():
                logger.warning("HuggingFaceProvider: credits exhausted: %s", exc)
                return _safe_contextual_result(
                    provider_failed=True,
                    reason_codes=["provider_credits_exhausted"],
                )
            if "429" in msg or "rate limit" in msg.lower():
                logger.warning("HuggingFaceProvider: rate limited: %s", exc)
                return _safe_contextual_result(
                    provider_failed=True,
                    reason_codes=["provider_rate_limited"],
                )
            logger.warning("HuggingFaceProvider: API error: %s", exc)
            return _safe_contextual_result(
                provider_failed=True,
                reason_codes=["provider_api_error"],
            )
        except Exception as exc:
            logger.warning(
                "HuggingFaceProvider: unexpected error: %s", exc
            )
            return _safe_contextual_result(
                provider_failed=True,
                reason_codes=["provider_unexpected_error"],
            )

        latency_ms = (time.perf_counter() - start) * 1000.0
        logger.debug(
            "HuggingFaceProvider: response in %.1fms from %s",
            latency_ms,
            self.model_id,
        )

        return self._parse_response(raw, text)


