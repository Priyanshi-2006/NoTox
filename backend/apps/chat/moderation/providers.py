def get_moderation_provider(name: Optional[str] = None) -> BaseModerationProvider:
    from django.conf import settings

    provider_name = (name or getattr(settings, "MODERATION_PROVIDER", "null")).lower()

    if provider_name == "mock":
        return MockProvider()

    if provider_name in ("local", "transformers"):
        return LocalTransformerProvider()

    if provider_name == "gemini":
        return GeminiProvider()

    if provider_name == "huggingface":
        return HuggingFaceProvider()

    # Default: NullProvider — preserves existing dev/test behaviour.
    return NullProvider()
