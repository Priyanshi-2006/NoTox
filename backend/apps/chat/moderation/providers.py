# Free Provider 1: Local Transformer Provider (100% Free, Offline, No Keys)
# ---------------------------------------------------------------------------

class LocalTransformerProvider(HuggingFaceProvider):
    """
    Local on-device moderation model running via HuggingFace transformers pipeline.
    100% free, runs offline on CPU/GPU, requires no API tokens, no credits, and no billing.
    Uses unitary/toxic-bert (or any text-classification model) locally.
    """

    def __init__(
        self,
        model_id: Optional[str] = None,
        max_input_length: Optional[int] = None,
        device: str = "cpu",
    ):
        from django.conf import settings

        BaseModerationProvider.__init__(self)
        self.model_id = (
            model_id
            or getattr(settings, "LOCAL_MODEL_ID", None)
            or getattr(settings, "HF_MODEL_ID", "unitary/toxic-bert")
        ).strip()
        self.max_input_length = (
            max_input_length
            if max_input_length is not None
            else int(getattr(settings, "HF_MAX_INPUT_LENGTH", 512))
        )
        self.device = device
        self._pipe = None

    def _get_pipeline(self):
        if self._pipe is None:
            try:
                from transformers import pipeline
                logger.info(
                    "LocalTransformerProvider: loading local model '%s' on %s...",
                    self.model_id,
                    self.device,
                )
                self._pipe = pipeline(
                    "text-classification",
                    model=self.model_id,
                    top_k=None,
                    device=self.device,
                )
            except Exception as exc:
                logger.error(
                    "LocalTransformerProvider: failed to load model '%s': %s",
                    self.model_id,
                    exc,
                )
                raise exc
        return self._pipe

    def _run_local_inference(self, input_text: str) -> object:
        pipe = self._get_pipeline()
        return pipe(input_text)

    async def evaluate_contextual(
        self,
        user,
        text: str,
        context: Optional[List[str]] = None,
    ) -> ContextualResult:
        start = time.perf_counter()
        context_prefix = self._build_context_prefix(context)
        input_text = self._truncate_input(context_prefix + text)

        try:
            raw = await asyncio.to_thread(self._run_local_inference, input_text)
        except Exception as exc:
            logger.warning("LocalTransformerProvider: inference error: %s", exc)
            return _safe_contextual_result(
                provider_failed=True,
                reason_codes=["local_model_error"],
            )

        latency_ms = (time.perf_counter() - start) * 1000.0
        logger.debug(
            "LocalTransformerProvider: response in %.1fms for %s",
            latency_ms,
            self.model_id,
        )
        return self._parse_response(raw, text)


