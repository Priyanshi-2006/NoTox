class GeminiProvider(BaseModerationProvider):
    """
    Google Gemini Moderation Provider using Google's free Gemini API.
    Free tier allows 15 requests/min and 1,500 requests/day at zero cost.
    Get a free API key at: https://aistudio.google.com/
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        model_id: Optional[str] = None,
        timeout: Optional[float] = None,
    ):
        super().__init__()
        from django.conf import settings

        self._api_key = (
            api_key
            or getattr(settings, "GEMINI_API_KEY", "")
            or ""
        ).strip()
        self.model_id = (
            model_id
            or getattr(settings, "GEMINI_MODEL_ID", "gemini-3.8-flash")
        ).strip()
        self.timeout = (
            timeout
            if timeout is not None
            else float(getattr(settings, "GEMINI_API_TIMEOUT", 15))
        )
        self._client = None

    def _get_client(self):
        if self._client is None:
            if not self._api_key:
                raise ValueError("GEMINI_API_KEY is not configured in settings or .env")
            from google import genai
            self._client = genai.Client(api_key=self._api_key)
        return self._client

    def _call_gemini_sync(self, prompt: str) -> str:
        client = self._get_client()
        # Primary model plus fallbacks in case of temporary 503 high demand spikes or deprecation
        models_to_try = [self.model_id]
        fallbacks = ["gemini-3.5-flash-lite", "gemini-3.5-flash", "gemini-flash-latest"]
        for fb in fallbacks:
            if fb not in models_to_try:
                models_to_try.append(fb)

        last_error = None
        for model_name in models_to_try:
            try:
                response = client.models.generate_content(
                    model=model_name,
                    contents=prompt,
                )
                if response and response.text:
                    return response.text
            except Exception as exc:
                last_error = exc
                err_str = str(exc)
                if "503" in err_str or "404" in err_str or "high demand" in err_str.lower():
                    logger.warning(
                        "Gemini model %r unavailable (%s), trying fallback...",
                        model_name,
                        exc,
                    )
                    continue
                raise exc
        raise last_error or RuntimeError("All Gemini models failed")

    async def evaluate_contextual(
        self,
        user,
        text: str,
        context: Optional[List[str]] = None,
    ) -> ContextualResult:
        if not self._api_key:
            logger.warning("GeminiProvider: GEMINI_API_KEY not set. Failing safe to allow.")
            return _safe_contextual_result(
                provider_failed=True,
                reason_codes=["gemini_missing_api_key"],
            )

        start = time.perf_counter()
        context_str = "\n".join(f"- {c}" for c in context[-5:]) if context else "(no context)"
        prompt = (
            "You are a nuanced chat moderation classifier. Your task is to detect GENUINE harm "
            "(direct threats, targeted harassment, hate speech, slurs) \xe2\x80\x94 NOT to flag casual "
            "language, compliments, idioms, or figurative speech.\n\n"
            "CRITICAL RULES \xe2\x80\x94 read carefully before scoring:\n"
            "1. INTENT matters more than individual words. A word that can be offensive in one "
            "context may be completely benign in another.\n"
            "2. Profanity used as an INTENSIFIER or COMPLIMENT is NOT harmful:\n"
            "   - 'you are fucking gorgeous' -> toxicity=0.0, insult=0.0 (compliment + intensifier)\n"
            "   - 'that was fucking amazing' -> toxicity=0.0 (enthusiastic praise)\n"
            "   - 'she is a badass' -> toxicity=0.0 (compliment)\n"
            "3. FIGURATIVE / IDIOMATIC language is NOT a threat:\n"
            "   - 'you killed the vibe' -> threat=0.0 (idiom: dampened the mood)\n"
            "   - 'she killed it on stage' -> threat=0.0 (idiom: performed brilliantly)\n"
            "   - 'this song is killing me' -> threat=0.0 (figurative: very moving)\n"
            "4. Only score HIGH when there is a DIRECT, TARGETED harmful action:\n"
            "   - 'I will kill you' -> threat=0.95 (direct personal threat)\n"
            "   - 'fuck you' -> toxicity=0.85, insult=0.85 (direct attack)\n"
            "   - 'you are worthless trash' -> harassment=0.9, insult=0.9\n"
            "5. Consider the PRECEDING CONVERSATION for full context before scoring.\n\n"
            f"Preceding conversation:\n{context_str}\n\n"
            f"Current message to evaluate:\n\"{text}\"\n\n"
            "Respond ONLY with a valid JSON object (no markdown, no extra text) containing:\n"
            "{\n"
            '  "toxicity_score": float (0.0 to 1.0),\n'
            '  "harassment_score": float (0.0 to 1.0),\n'
            '  "threat_score": float (0.0 to 1.0),\n'
            '  "insult_score": float (0.0 to 1.0),\n'
            '  "sarcasm_detected": bool,\n'
            '  "intent_label": "attack" | "harassment" | "threat" | "insult" | "mockery" | "banter" | "criticism" | "quotation" | "disagreement" | "neutral",\n'
            '  "target_type": "person" | "group" | "idea" | "action" | "self" | "none"\n'
            "}"
        )

        try:
            raw_text = await asyncio.wait_for(
                asyncio.to_thread(self._call_gemini_sync, prompt),
                timeout=self.timeout,
            )
            clean_json = raw_text.strip()
            if clean_json.startswith("```json"):
                clean_json = clean_json[7:]
            if clean_json.startswith("```"):
                clean_json = clean_json[3:]
            if clean_json.endswith("```"):
                clean_json = clean_json[:-3]
            data = json.loads(clean_json.strip())

            return _safe_contextual_result(
                toxicity_score=float(data.get("toxicity_score", 0.0)),
                harassment_score=float(data.get("harassment_score", 0.0)),
                threat_score=float(data.get("threat_score", 0.0)),
                insult_score=float(data.get("insult_score", 0.0)),
                sarcasm_detected=bool(data.get("sarcasm_detected", False)),
                intent_label=str(data.get("intent_label", "unknown")),
                target_type=str(data.get("target_type", "unknown")),
                confidence=0.9,
                contextual_analysis_performed=True,
            )
        except Exception as exc:
            logger.warning("GeminiProvider: error: %s", exc)
            return _safe_contextual_result(
                provider_failed=True,
                reason_codes=["gemini_error"],
            )

    async def evaluate(self, user, text: str) -> ProviderResult:
        self.call_count += 1
        ctx = await self.evaluate_contextual(user, text)
        if ctx.provider_failed:
            return ProviderResult(verdict="allowed", reason="gemini_fail_safe")
        verdict = "blocked" if (ctx.toxicity_score >= 0.85 or ctx.threat_score >= 0.80) else "allowed"
        return ProviderResult(verdict=verdict, reason="gemini_eval")


